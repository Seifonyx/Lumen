import { extractMemoryOps, hideMemoryLines, sameMemory, findMemory, memoryInstructions } from '../../src/lib/memory';
let fails = 0;
const check = (c: boolean, l: string) => { console.log(`${c ? 'PASS' : 'FAIL'}  ${l}`); if (!c) fails++; };
const r = extractMemoryOps('Got it, I will.\n\n[[remember: Works as a clinical pharmacist]]\n[[ forget : Prefers English ]]');
check(r.text === 'Got it, I will.' && r.remember[0] === 'Works as a clinical pharmacist' && r.forget[0] === 'Prefers English', 'extracts and strips markers');
const ar = extractMemoryOps('تمام\n[[remember: يفضل الردود بالعربية]]');
check(ar.text === 'تمام' && ar.remember[0] === 'يفضل الردود بالعربية', 'Arabic memory');
check(extractMemoryOps('no markers [[link]] here').text === 'no markers [[link]] here', 'leaves other brackets');
for (const partial of ['Hi\n[', 'Hi\n[[', 'Hi\n[[rem', 'Hi\n[[remember', 'Hi\n[[remember: Works as', 'Hi\n[[remember: x]', 'Hi\n[[forget: y']) check(hideMemoryLines(partial).trim() === 'Hi', `hides partial ${JSON.stringify(partial)}`);
check(hideMemoryLines('Hi [[remember: a]] there') === 'Hi  there', 'hides complete marker mid-stream');
check(hideMemoryLines('see [docs](x)') === 'see [docs](x)', 'normal links untouched');
check(sameMemory('Works as a clinical pharmacist', 'works as a clinical pharmacist.'), 'same memory ignoring case/punctuation');
check(sameMemory('Prefers English', 'The user prefers English'), 'containment counts as same');
check(!sameMemory('Works in Cairo', 'Lives in Alexandria'), 'different memories differ');
const items: any = [{ id: '1', text: 'Prefers replies in English', updatedAt: 1 }];
check(findMemory(items, 'prefers replies in english')?.id === '1', 'forget finds the memory');
const ins = memoryInstructions(items, true);
check(ins.includes('- Prefers replies in English') && ins.includes('[[remember:') && ins.includes('lasting fact') && ins.includes('other people'), 'instructions list memories + rules');
check(memoryInstructions([], false).includes('only when the user explicitly asks') && memoryInstructions([], false).includes('no saved memories'), 'ask-only mode');
const many: any = Array.from({ length: 100 }, (_, i) => ({ id: String(i), text: 'x'.repeat(400), updatedAt: i }));
check(memoryInstructions(many, true).length < 11000, 'prompt budget respected');
console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
process.exit(fails ? 1 : 0);
