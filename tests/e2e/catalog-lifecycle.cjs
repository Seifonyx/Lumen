// Real Settings/picker updates with deterministic discovery and browser lifecycle events.
const {chromium,webkit}=require('playwright');
const assert=require('node:assert/strict');
const {profile}=require('./helpers/preview-profile.cjs');
const base=process.env.MR_TEST_URL || 'http://localhost:5190/';
const cors={'access-control-allow-origin':'*','access-control-allow-headers':'*','access-control-allow-methods':'GET,POST,OPTIONS'};
const initial=Date.now();
(async()=>{
 const browser=await(process.env.MR_WEBKIT?webkit:chromium).launch();
 try {for(const width of [390,1280]) {
  const context=await browser.newContext({viewport:{width,height:844},isMobile:width<900,hasTouch:width<900,serviceWorkers:'block'});
  const uid=`preview-catalog-${width}`;
  await profile(context,uid,'dark');
  let names=['gemini-flash-latest'],status=200,calls=0;
  await context.route('**/generativelanguage.googleapis.com/**',async route=>{
   if(route.request().method()==='OPTIONS')return route.fulfill({status:204,headers:cors});
   calls++;
   assert(route.request().url().includes('/models?'),'no inference is needed to refresh metadata');
   return route.fulfill({status,headers:cors,json:status===200?{models:names.map(name=>({name:`models/${name}`,displayName:name,inputTokenLimit:128000,supportedGenerationMethods:['generateContent']}))}:{error:{message:'Controlled catalogue error'}}});
  });
  const page=await context.newPage(),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.clock.setFixedTime(initial);
  await page.goto(new URL('privacy.html',base).href);
  await page.evaluate(()=>localStorage.setItem('mr.catalog',JSON.stringify({models:[{id:'gemini:other-account-secret-model',label:'Other account'}],defaults:[],providers:{google:true},errors:[]})));
  await page.goto(base);
  await page.locator('.composer textarea').waitFor();
  await page.waitForFunction(uid=>JSON.parse(localStorage.getItem(`mr.catalog.v2.${uid}`)||'null')?.value.providerStatus?.gemini?.state==='ready',uid);
  assert.equal(calls,1);
  assert.equal(await page.evaluate(()=>localStorage.getItem('mr.catalog')),null,'discard unscoped legacy cache');
  if(width<900)await page.locator('.menu-btn').click();
  await page.locator('.sidebar-foot').click();
  await page.locator('.settings-tabs').getByRole('button',{name:'Models',exact:true}).click();
  await page.getByRole('button',{name:'Browse models',exact:true}).click();
  await page.getByRole('searchbox',{name:'Search available models'}).fill('newcomer');
  await page.evaluate(()=>{window.dispatchEvent(new Event('focus'));document.dispatchEvent(new Event('visibilitychange'));});
  await page.waitForTimeout(100);
  assert.equal(calls,1,'fresh metadata makes no extra provider requests on resume');
  names.push('gemini-newcomer');
  await page.clock.setFixedTime(initial+11*60_000);
  await page.evaluate(()=>window.dispatchEvent(new Event('focus')));
  await page.locator('.model-list.add').getByText('gemini-newcomer',{exact:true}).waitFor();
  assert.equal(calls,2,'expired metadata refreshes once on resume');
  assert.equal(await page.getByRole('searchbox',{name:'Search available models'}).inputValue(),'newcomer','refresh preserves search and open settings');
  assert(!JSON.stringify(await page.evaluate(uid=>JSON.parse(localStorage.getItem(`mr.catalog.v2.${uid}`)),uid)).includes('other-account-secret-model'));
  status=503;
  await page.getByRole('button',{name:'Refresh',exact:true}).click();
  await page.waitForFunction(uid=>JSON.parse(localStorage.getItem(`mr.catalog.v2.${uid}`))?.value.providerStatus.gemini.state==='stale',uid);
  assert.equal(calls,4,'transient failure retries once');
  assert(await page.locator('.model-list.add').getByText('gemini-newcomer',{exact:true}).isVisible(),'same-credential transient failure preserves known models');
  status=401;
  await page.getByRole('button',{name:'Refresh',exact:true}).click();
  await page.waitForFunction(uid=>JSON.parse(localStorage.getItem(`mr.catalog.v2.${uid}`))?.value.providerStatus.gemini.errorKind==='auth',uid);
  assert.equal(calls,5,'rejected credentials are never retried');
  assert.equal(await page.locator('.model-list.add').getByText('gemini-newcomer',{exact:true}).count(),0,'rejected credentials evict old catalogue');
  await page.reload();
  await page.locator('.composer textarea').waitFor();
  await page.waitForFunction(uid=>JSON.parse(localStorage.getItem(`mr.catalog.v2.${uid}`))?.value.providerStatus.gemini.errorKind==='auth',uid);
  assert.equal(await page.evaluate(uid=>JSON.parse(localStorage.getItem(`mr.catalog.v2.${uid}`)).value.models.length,uid),0,'reload cannot resurrect evicted metadata');
  assert.deepEqual(errors,[]);
  console.log(`PASS catalog lifecycle ${process.env.MR_WEBKIT?'webkit':'chromium'} ${width}px: scope, TTL, resume, live propagation, stable query, transient retention and auth eviction`);
  await context.close();
 }} finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
