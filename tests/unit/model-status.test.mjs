import assert from 'node:assert/strict';
import { isActiveModel, isRetiredModel, isExcludedModel, isUnavailableFailure, keepModelChoice } from '../../src/lib/ai/model-status.js';
assert.ok(isRetiredModel('gemini:gemini-2.0-flash'));
assert.ok(isRetiredModel('gemini:gemini-3-pro-preview'));
assert.ok(isRetiredModel('groq:llama-3.3-70b-versatile'));
assert.ok(!isRetiredModel('gemini:gemini-2.5-flash'));
assert.ok(!isRetiredModel('openrouter:meta-llama/llama-3.3-70b:free'));
assert.ok(isExcludedModel('gemini:gemini-3.1-pro-preview'));
assert.ok(isExcludedModel('gemini:gemini-pro-latest'));
assert.ok(isUnavailableFailure(404, 'Model x is not found'));
assert.ok(isUnavailableFailure(400, 'This model has been decommissioned'));
assert.ok(isUnavailableFailure(429, 'GenerateRequestsPerDayPerProjectPerModel-FreeTier, limit: 0'));
assert.ok(!isUnavailableFailure(429, 'FreeTier rate limit: 50'));
assert.ok(!isUnavailableFailure(401, 'API key invalid'));
assert.ok(!isUnavailableFailure(403, 'API key not allowed for this website'));
assert.ok(!isUnavailableFailure(400, 'Unsupported image input'));
assert.ok(!isUnavailableFailure(503, 'Model is overloaded'));
assert.ok(!isActiveModel({ active: false }));
assert.ok(!isActiveModel({ disabled: true }));
assert.ok(!isActiveModel({ expiration_date: '2025-01-01' }));
assert.ok(isActiveModel({ expiration_date: '2099-01-01' }));
const catalog = { models: [{ id: 'gemini:gemini-flash-latest' }], failedProviders: ['groq'] };
assert.ok(keepModelChoice('groq:openai/gpt-oss-120b', catalog));
assert.ok(!keepModelChoice('groq:llama-3.3-70b-versatile', catalog));
assert.ok(keepModelChoice('gemini:missing', catalog));
assert.ok(keepModelChoice('groq:missing', { models: [], failedProviders: [] }));
console.log('PASS retired, disabled and expired models; discovery availability changes preserve saved choices');
