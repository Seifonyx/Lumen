import assert from 'node:assert/strict';
import { catalogScope, readCatalogCache, writeCatalogCache } from '../../src/lib/ai/catalog-cache.js';
const data=new Map(),storage={getItem:key=>data.get(key)||null,setItem:(key,value)=>data.set(key,value),removeItem:key=>data.delete(key)};
const original={gemini:'synthetic-private-key',providerRelayUrl:'https://relay.example'};
const scope=await catalogScope('alice',original);
assert(!scope.includes('synthetic'));
assert.notEqual(scope,await catalogScope('bob',original));
assert.notEqual(scope,await catalogScope('alice',{...original,gemini:'replacement'}));
assert.notEqual(scope,await catalogScope('alice',{...original,providerRelayUrl:'https://other.example'}));
assert.notEqual(scope,await catalogScope('alice',{...original,cloudflareAccountId:'a'.repeat(32)}));
assert.equal(scope,await catalogScope('alice',{...original,github:'unrelated'}),'GitHub keys do not invalidate model metadata');
const catalog={models:[{id:'gemini:model',context:64000}],defaults:['gemini:model'],providers:{google:true},errors:[]};
writeCatalogCache(storage,'alice',scope,catalog,1000);
assert.deepEqual(readCatalogCache(storage,'alice',scope,2000),catalog);
assert.equal(readCatalogCache(storage,'bob',scope,2000),null);
assert.equal(readCatalogCache(storage,'alice','other-credential',2000),null);
assert.equal(readCatalogCache(storage,'alice',scope,1000+25*3600_000),null);
assert.equal(readCatalogCache(storage,'alice',scope,900),null,'clock rollback does not grant indefinite freshness');
assert(![...data.values()].join('').includes('synthetic-private-key'),'never persist raw credentials in cache scope');
data.set('mr.catalog',JSON.stringify(catalog));
assert.equal(readCatalogCache(storage,'nobody',scope,2000),null,'legacy unscoped cache is never imported');
data.set('mr.catalog.v2.alice','{bad'); assert.equal(readCatalogCache(storage,'alice',scope,2000),null);
const denied={getItem(){throw Error('denied');},setItem(){throw Error('denied');}};
assert.equal(readCatalogCache(denied,'alice',scope),null);writeCatalogCache(denied,'alice',scope,catalog);
console.log('PASS credential/account/endpoint isolation, secret-free scope, expiry, corrupt/denied storage and legacy-cache rejection');
