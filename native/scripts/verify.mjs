import assert from 'node:assert/strict';
import { readFileSync, existsSync, readdirSync } from 'node:fs';
const config=JSON.parse(readFileSync('native/capacitor.config.json','utf8'));
assert.equal(config.appId,'io.github.seifonyx.lumen.demo');
assert.equal(config.webDir,'www');
assert.equal(config.loggingBehavior,'none');
assert.equal(config.server.iosScheme,'capacitor');
assert.equal(config.server.url,undefined);
assert.equal(config.plugins.CapacitorHttp.enabled,false);
const dependencies=JSON.parse(readFileSync('native/package.json','utf8'));
for(const version of Object.values({...dependencies.dependencies,...dependencies.devDependencies})) assert.equal(version,'8.6.0');
const graph=JSON.parse(readFileSync('native/www/demo-build.json','utf8'));
assert.equal(graph.presentation,'canvas');
assert(graph.modules.some(p=>p==='src/lib/canvas-presentation.on.ts'));
for(const module of ['native/demo/account.ts','native/demo/sync.ts','native/demo/lifecycle.ts','native/integration/auth.ts','native/integration/provider.ts','native/integration/sync.ts'])assert(graph.modules.includes(module),module);
assert(graph.modules.every(p=>!p.startsWith('native/authorization/')));
assert(graph.modules.every(p=>!/^qa\/iphone\/(fixtures|main)/.test(p)));
assert(graph.modules.every(p=>!/^src\/lib\/(firebase|sync)\.ts$|^src\/firebase-config\.json$|^src\/pwa\/register\.ts$/.test(p)));
assert(!existsSync('native/www/sw.js'));
assert(readdirSync('native/www/assets').some(n=>n.endsWith('.woff2')));
// The Canvas mark Logo loads as /icon.svg must be packaged (a missing file shows a broken image at launch).
assert(existsSync('native/www/icon.svg') && readFileSync('native/www/icon.svg','utf8').includes('<svg'));
const html=readFileSync('native/www/index.html','utf8');
assert(html.includes("connect-src 'self' data: blob:"));
assert(!html.includes('https://'));
const swift=readFileSync('native/DemoViewController.swift','utf8');
assert(swift.includes('compileContentRuleList'));
assert(swift.includes('decisionHandler(.cancel)'));
assert(swift.includes('decisionHandler(.deny)'));
const workflow=readFileSync('.github/workflows/ios-demo.yml','utf8');
assert(workflow.includes('runs-on: macos-26'));
assert(!/secrets\.|workflow_call|pull_request_target/.test(workflow));
console.log('PASS native config, Canvas graph, no Firebase/PWA/private fixtures, bundled fonts and offline barriers');
